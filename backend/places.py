def _fold(name: Any) -> str:
    """A name in the form the tables are keyed by."""
    text = " ".join(str(name or "").split())
    # An apostrophe is written three ways in these posts and OpenStreetMap
    # uses a fourth. Normalised so "Слов'янськ" matches whichever arrives.
    for odd in ("’", "ʼ", "`", "´"):
        text = text.replace(odd, "'")
    return text.casefold()


def _index() -> dict[str, dict[str, Any]]:
    """Every name and alias, folded, pointing at a finished answer."""
    out: dict[str, dict[str, Any]] = {}
    for table, default, kind, category in (
        (CITIES, CITY_HALF, "town", "place"),
        (REGIONS, OBLAST_HALF, "administrative", "boundary"),
    ):
        for name, (lat, lon) in table.items():
            half = WIDE.get(name, default)
            out[_fold(name)] = {
                "lat": lat, "lon": lon, "name": name,
                "kind": kind, "category": category,
                "bbox": [round(lat - half, 4), round(lat + half, 4),
                         round(lon - half, 4), round(lon + half, 4)],
                # No boundary. That is the one thing this table cannot carry
                # -- an oblast outline is thousands of points -- so a region
                # is drawn from its extent until the real shape arrives.
                "shape": None,
                # So the caller knows this came from here rather than from the
                # gazetteer, and can ask for the outline in the background.
                "built_in": True,
            }
    for alias, real in ALIASES.items():
        found = out.get(_fold(real))
        if found:
            out[_fold(alias)] = found
    return out


KNOWN = _index()


def lookup(name: Any) -> dict[str, Any] | None:
    """Where a place is, if it is one of the ones that comes up every night."""
    found = KNOWN.get(_fold(name))
    return dict(found) if found else None


def count() -> dict[str, int]:
    """What is in here, for the panel to say."""
    return {"cities": len(CITIES), "regions": len(REGIONS),
            "aliases": len(ALIASES), "names": len(KNOWN)}
