"""The places these reports name, built in, so most lookups cost nothing.

The gazetteer is correct and it is slow, and the slowness is not its fault.
Nominatim asks to be called at most once a second, that is honoured, and so
placing twenty reports took fourteen and a half seconds -- measured. On a busy
night the map fills in over a minute, one mark at a time, which from the
outside is indistinguishable from a layer that does not work.

But the names in these reports are not arbitrary. They are the same two dozen
oblasts and the same hundred cities, every night, for years: Сумщина,
Харківська область, Нікополь, Київ, Белгородская область. A gazetteer request
for "Харків" is a round trip to Germany to be told a thing that has not moved
since 1654.

So they are here. A dict lookup instead of a network call, which turns the
common case from 740 ms into about a microsecond and, just as usefully, removes
a whole class of misses: no transliteration to get wrong, no rate limit to
queue behind, nothing to be down.

What this is and is not:

  It is a CENTRE and an EXTENT. An oblast entry is the middle of the province
  and roughly how big it is, which is what a mark needs. It is not a boundary
  -- those are thousands of points and they come from Nominatim, which is
  asked for them in the background once the mark is already on the map.

  It is not a replacement for the gazetteer. Anything not here still goes to
  Nominatim exactly as before; this is a cache that ships with the app, not a
  different way of deciding where things are.

  Every coordinate here is a well-known place centre. Where a value was not
  certain, the place is not in the table -- an absent entry costs a lookup,
  and a wrong one puts a marker in the wrong province, which is the failure
  this whole module exists to prevent.
"""

